// One-shot generator: seed-data.ts -> SQL migration to populate public.tests
// Usage: node tools/generate-tests-seed.cjs > supabase/migrations/20260618190000_seed_remaining_tests.sql

const fs = require('fs');
const path = require('path');
const os = require('os');
const ts = require('typescript');

const srcPath = path.join(__dirname, '..', 'src', 'data', 'seed-data.ts');
const src = fs.readFileSync(srcPath, 'utf-8');
const out = ts.transpileModule(src, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
});

const tmpPath = path.join(os.tmpdir(), `seed-data-${Date.now()}.cjs`);
fs.writeFileSync(tmpPath, out.outputText, 'utf-8');
const mod = require(tmpPath);
fs.unlinkSync(tmpPath);

const tests = mod.tests;

const FREE = new Set(['INT', 'E-3', 'A-2', 'D-1']);

function esc(s) {
  return String(s).replace(/'/g, "''");
}
function jsonbLit(obj) {
  return JSON.stringify(obj).replace(/'/g, "''");
}

let sql = `-- ============================================================
-- Auto-generated seed for public.tests (non-INT tests)
-- Generated by tools/generate-tests-seed.cjs from src/data/seed-data.ts
-- Idempotent via ON CONFLICT (id) DO UPDATE
-- ============================================================

`;

let count = 0;
for (const t of tests) {
  if (!t.questions || t.questions.length === 0) continue;
  if (t.id === 'INT') continue;
  count++;

  const subdomains = [...new Set(t.questions.map((q) => q.subdomain))];
  const isFree = FREE.has(t.id);
  const price = isFree ? 0 : 2900;

  sql += `INSERT INTO public.tests (
  id, name, category, related_syndrome, description,
  question_count, duration_minutes,
  is_recommended, is_coming_soon,
  is_integrated, is_free, price_krw,
  subdomains, questions
) VALUES (
  '${esc(t.id)}',
  '${esc(t.name)}',
  '${esc(t.category)}',
  '${esc(t.relatedSyndrome)}',
  '${esc(t.description)}',
  ${t.questions.length},
  3,
  false,
  ${t.comingSoon === true ? 'true' : 'false'},
  false,
  ${isFree ? 'true' : 'false'},
  ${price},
  '${jsonbLit(subdomains)}'::jsonb,
  '${jsonbLit(t.questions)}'::jsonb
)
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  category = EXCLUDED.category,
  related_syndrome = EXCLUDED.related_syndrome,
  description = EXCLUDED.description,
  question_count = EXCLUDED.question_count,
  subdomains = EXCLUDED.subdomains,
  questions = EXCLUDED.questions,
  is_free = EXCLUDED.is_free,
  price_krw = EXCLUDED.price_krw;

`;
}

process.stderr.write(`Generated SQL for ${count} tests\n`);
process.stdout.write(sql);
